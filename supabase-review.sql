-- 缺陷报告审核流程迁移（针对线上实际使用的 public.bug_reports 表）。
-- 说明：仓库里的 supabase.sql 建的是 public.bugs，但前端/保活实际使用 public.bug_reports。
-- 本文件可重复执行，全部操作都作用在 public.bug_reports 上。
-- 在 Supabase SQL Editor 中整段执行。

create extension if not exists pgcrypto;

-- 1) 审核人配置：0=非审核人，1=第一审核，2=第二审核，由超级管理员在用户管理中设置。
alter table public.profiles add column if not exists review_stage integer not null default 0;
alter table public.profiles drop constraint if exists profiles_review_stage_check;
alter table public.profiles add constraint profiles_review_stage_check check (review_stage in (0, 1, 2));

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin' and active); $$;

create or replace function public.current_department()
returns text language sql stable security definer set search_path = public
as $$ select department from public.profiles where id = auth.uid() and active; $$;

create or replace function public.is_reviewer()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and review_stage in (1, 2) and active); $$;

create or replace function public.current_review_stage()
returns integer language sql stable security definer set search_path = public
as $$ select coalesce((select review_stage from public.profiles where id = auth.uid() and active), 0); $$;

-- 超级管理员账号可编辑，但禁止改变“是否超管”。
create or replace function public.enforce_profile_role_guard()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if old.role = 'admin' and new.role <> 'admin' then
    raise exception '不能取消超级管理员身份';
  end if;
  if new.role = 'admin' and old.role <> 'admin' then
    raise exception '不能将普通用户提升为超级管理员';
  end if;
  return new;
end $$;

do $$
begin
  if exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'profiles') then
    execute 'drop trigger if exists profiles_role_guard on public.profiles';
    execute 'create trigger profiles_role_guard before update on public.profiles for each row execute function public.enforce_profile_role_guard()';
  end if;
end $$;

-- 2) 为 bug_reports 补齐可能缺失的字段（含审核字段）。
do $$
begin
  if not exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'bug_reports') then
    raise exception '找不到 public.bug_reports 表，请确认线上表名。';
  end if;
end $$;

alter table public.bug_reports add column if not exists bug_no bigint generated by default as identity;
create unique index if not exists bug_reports_bug_no_key on public.bug_reports (bug_no);
alter table public.bug_reports add column if not exists submitter_id uuid references auth.users(id);
alter table public.bug_reports add column if not exists transfer_from text not null default '';
alter table public.bug_reports add column if not exists transfer_note text not null default '';
alter table public.bug_reports add column if not exists follow_up_id uuid references auth.users(id);
alter table public.bug_reports add column if not exists assigned_at timestamptz;
alter table public.bug_reports add column if not exists assignee_department text not null default '';
alter table public.bug_reports add column if not exists assignee_id uuid references public.developers(id) on delete set null;
alter table public.bug_reports add column if not exists review_note text not null default '';
alter table public.bug_reports add column if not exists reviewer_id uuid references auth.users(id);

-- 3) 动态替换 status 约束（无论旧约束叫什么名字），并设置默认值。
do $$
declare c record;
begin
  for c in
    select conname from pg_constraint
    where conrelid = 'public.bug_reports'::regclass and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%status%'
  loop
    execute format('alter table public.bug_reports drop constraint %I', c.conname);
  end loop;
  execute 'alter table public.bug_reports add constraint bug_reports_status_check check (status in (''pending_review_1'',''pending_review_2'',''rejected'',''postponed'',''open'',''in_progress'',''resolved''))';
  execute 'alter table public.bug_reports alter column status set default ''pending_review_1''';
end $$;

create index if not exists bug_reports_status_idx on public.bug_reports (status);
create index if not exists bug_reports_created_at_idx on public.bug_reports (created_at desc);

-- 4) 审核操作历史（重建为指向 bug_reports）。
drop table if exists public.bug_review_events;
create table public.bug_review_events (
  id uuid primary key default gen_random_uuid(),
  bug_id uuid not null references public.bug_reports(id) on delete cascade,
  stage integer not null check (stage in (1, 2)),
  action text not null check (action in ('approve', 'reject')),
  note text not null default '',
  reviewer_id uuid references auth.users(id),
  reviewer_name text not null default '',
  created_at timestamptz not null default now()
);
create index bug_review_events_bug_idx on public.bug_review_events (bug_id, created_at asc);
alter table public.bug_review_events enable row level security;

drop policy if exists "team read bug review events" on public.bug_review_events;
create policy "team read bug review events"
on public.bug_review_events for select to authenticated using (true);

drop policy if exists "reviewer create bug review events" on public.bug_review_events;
create policy "reviewer create bug review events"
on public.bug_review_events for insert to authenticated
with check (reviewer_id = auth.uid() and (public.is_reviewer() or public.is_admin()));

-- 5) bug_reports 的 RLS 策略（读取 / 新建 / 更新 / 删除）。
alter table public.bug_reports enable row level security;

drop policy if exists "internal read bug reports" on public.bug_reports;
create policy "internal read bug reports"
on public.bug_reports for select to authenticated using (true);

drop policy if exists "internal create bug reports" on public.bug_reports;
create policy "internal create bug reports"
on public.bug_reports for insert to authenticated
with check (
  (submitter_id = auth.uid() or submitter_id is null)
  and status = 'pending_review_1'
  and fix_plan = ''
  and assignee = ''
  and resolved_at is null
  and cardinality(attachment_urls) <= 8
);

drop policy if exists "internal update bug reports" on public.bug_reports;
create policy "internal update bug reports"
on public.bug_reports for update to authenticated
using (
  submitter_id = auth.uid()
  or follow_up_id = auth.uid()
  or public.is_admin()
  or public.current_department() = assignee_department
  or public.is_reviewer()
)
with check (
  status in ('pending_review_1', 'pending_review_2', 'rejected', 'postponed', 'open', 'in_progress', 'resolved')
  and char_length(fix_plan) <= 3000
  and char_length(assignee) <= 40
  and char_length(assignee_department) <= 60
  and char_length(review_note) <= 1000
);

drop policy if exists "internal delete bug reports" on public.bug_reports;
create policy "internal delete bug reports"
on public.bug_reports for delete to authenticated
using (submitter_id = auth.uid() or public.is_admin());

-- 6) 附件删除策略（取消上传时清理附件）。
drop policy if exists "internal delete bug attachments" on storage.objects;
create policy "internal delete bug attachments"
on storage.objects for delete to authenticated
using (bucket_id = 'bug-attachments');

-- 提示：如果 public.bug_reports 上曾经创建过其它名字的旧策略，
-- 它们仍会以“宽松策略”的形式并存，不影响本次功能；如需清理可自行核对 Supabase 策略列表。
